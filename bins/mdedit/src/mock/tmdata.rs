pub fn idx(v: &[P], pid: u32) -> usize {
    v.iter().position(|x| x.pid == pid).unwrap_or(0)
}

/// Pids of the children of `pid`, in list order.
pub fn kids(v: &[P], pid: u32) -> Vec<usize> {
    v.iter()
        .enumerate()
        .filter(|(_, x)| x.ppid == pid && x.pid != pid)
        .map(|(i, _)| i)
        .collect()
}

/// The sum of a subtree (the row itself and everything below it).
pub fn subtree(v: &[P], i: usize) -> Vec<usize> {
    let mut out = vec![i];
    let mut k = 0;
    while k < out.len() {
        let pid = v[out[k]].pid;
        for c in kids(v, pid) {
            out.push(c);
        }
        k += 1;
    }
    out
}

