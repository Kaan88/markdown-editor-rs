pub fn fmt_mem(mb: f32) -> String {
    if mb <= 0.04 {
        "0 MB".into()
    } else if mb >= 1000.0 {
        format!("{:.1} GB", mb / 1024.0)
    } else if mb < 10.0 {
        format!("{:.1} MB", mb)
    } else {
        format!("{:.0} MB", mb)
    }
}

pub fn fmt_rate(v: f32, unit: &str) -> String {
    if v < 0.05 {
        format!("0 {unit}")
    } else if v < 10.0 {
        format!("{:.1} {unit}", v)
    } else {
        format!("{:.0} {unit}", v)
    }
}
