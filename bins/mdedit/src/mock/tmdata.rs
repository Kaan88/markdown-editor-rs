/// A deterministic, smooth-ish series in 0..1: `n` samples, `base` level, `amp` swing, `seed`.
pub fn series(n: usize, base: f32, amp: f32, seed: u32) -> Vec<f32> {
    let mut s = seed.wrapping_mul(2654435761).wrapping_add(12345);
    let mut v = Vec::with_capacity(n);
    let mut cur = base;
    for i in 0..n {
        s = s.wrapping_mul(1664525).wrapping_add(1013904223);
        let r = ((s >> 16) & 0x7fff) as f32 / 32767.0 - 0.5;
        let wave = ((i as f32) * 0.21 + seed as f32).sin() * 0.5;
        cur = cur * 0.55 + (base + wave * amp * 0.6 + r * amp) * 0.45;
        v.push(cur.clamp(0.0, 1.0));
    }
    v
}

